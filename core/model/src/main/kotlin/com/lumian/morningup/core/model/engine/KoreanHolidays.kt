package com.lumian.morningup.core.model.engine

import java.time.LocalDate

/** 공휴일 달력. 목록 밖 연도는 공휴일이 없는 것으로 봐요. */
interface HolidayCalendar {
    fun isHoliday(date: LocalDate): Boolean

    /** 이 연도의 목록이 있으면 true. 없으면 설정에 '공휴일 목록을 업데이트해 주세요'를 띄워요. */
    fun covers(year: Int): Boolean
}

/**
 * 한국 관공서 공휴일과 대체공휴일 2026~2027 (F13).
 * 2026년 법 개정으로 노동절(5/1)과 제헌절(7/17)이 공휴일이 됐어요.
 * 2027년 토요일과 겹치는 노동절, 제헌절의 대체공휴일은 확실하지 않아 넣지 않았어요(ADR 0002).
 * 해마다 정부 발표를 보고 다음 해 목록을 더해요.
 */
object KoreanHolidays : HolidayCalendar {
    private val dates: Set<LocalDate> = listOf(
        // 2026
        "2026-01-01", // 신정
        "2026-02-16", "2026-02-17", "2026-02-18", // 설날 연휴
        "2026-03-01", "2026-03-02", // 삼일절, 일요일이라 대체
        "2026-05-01", // 노동절
        "2026-05-05", // 어린이날
        "2026-05-24", "2026-05-25", // 부처님오신날, 일요일이라 대체
        "2026-06-03", // 제9회 전국동시지방선거
        "2026-06-06", // 현충일(토요일, 대체 없음)
        "2026-07-17", // 제헌절
        "2026-08-15", "2026-08-17", // 광복절, 토요일이라 대체
        "2026-09-24", "2026-09-25", "2026-09-26", // 추석 연휴(토요일과 겹쳐도 대체 없음)
        "2026-10-03", "2026-10-05", // 개천절, 토요일이라 대체
        "2026-10-09", // 한글날
        "2026-12-25", // 성탄절
        // 2027
        "2027-01-01",
        "2027-02-06", "2027-02-07", "2027-02-08", "2027-02-09", // 설날 연휴, 일요일과 겹쳐 대체
        "2027-03-01",
        "2027-05-01", // 노동절(토요일)
        "2027-05-05",
        "2027-05-13", // 부처님오신날
        "2027-06-06", // 현충일(일요일, 대체 없음)
        "2027-07-17", // 제헌절(토요일)
        "2027-08-15", "2027-08-16", // 광복절, 일요일이라 대체
        "2027-09-14", "2027-09-15", "2027-09-16", // 추석 연휴
        "2027-10-03", "2027-10-04", // 개천절, 일요일이라 대체
        "2027-10-09", "2027-10-11", // 한글날, 토요일이라 대체
        "2027-12-25", "2027-12-27", // 성탄절, 토요일이라 대체
    ).map(LocalDate::parse).toSet()

    private val years = 2026..2027

    override fun isHoliday(date: LocalDate): Boolean = date in dates

    override fun covers(year: Int): Boolean = year in years
}
